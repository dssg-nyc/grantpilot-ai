import Anthropic from "@anthropic-ai/sdk";
import type { SupabaseClient } from "@supabase/supabase-js";
import { anthropic } from "@/lib/anthropic/client";
import { SCOUT_TOOLS } from "@/lib/anthropic/scout/tools";
import { recordFinding } from "@/lib/anthropic/scout/record-finding";
import { searchOpportunities } from "@/lib/anthropic/agent/tool-handlers";
import type { ScoutFinding } from "@/types/scout";

export type ScoutEvent =
  /** Human-readable progress, e.g. "Searching the web for …". */
  | { type: "activity"; label: string; detail?: string }
  /** One verified opportunity, already persisted. */
  | { type: "finding"; finding: ScoutFinding }
  /** Tokens of the agent's closing summary. */
  | { type: "summary_delta"; text: string }
  | { type: "error"; message: string }
  | { type: "done"; summary: string; findingCount: number; searchesUsed: number };

/**
 * Claude Opus 5 — this is a long-horizon research task where the difference
 * between a good and a mediocre model shows up directly as wasted staff weeks
 * chasing bad leads. It is meaningfully more expensive per run than the
 * conversational assistant's Sonnet; if cost becomes the binding constraint,
 * `claude-sonnet-5` is the drop-in step down (it supports the same
 * `web_search_20260209` / `web_fetch_20260209` tools and the same effort ladder).
 */
const MODEL = "claude-opus-5";
const EFFORT = "high" as const;
/**
 * Thinking is on by default on Opus 5 and max_tokens caps thinking AND output
 * together, so this needs real headroom or long research turns truncate
 * mid-sentence. Streaming is required at this size.
 */
const MAX_TOKENS = 16000;
/** Tool rounds, not searches — one round can hold several parallel tool calls. */
const MAX_ROUNDS = 14;

const KICKOFF =
  "Begin the research run described in your instructions. Work through it end to end: check what the app already has, search the web, verify each opportunity at its source, record each one as you confirm it, then write your closing summary.";

export interface ScoutContext {
  supabase: SupabaseClient;
  runId: string;
  orgId: string;
}

function activityForToolStart(name: string, input: Record<string, unknown>): ScoutEvent | null {
  if (name === "check_known_opportunities") {
    const q = typeof input.query === "string" ? input.query : undefined;
    return { type: "activity", label: "Checking grants already in your database", detail: q };
  }
  return null;
}

/**
 * Drives one funding-scout research run to completion, streaming progress as
 * it goes. Findings are persisted the moment the agent records them, so a
 * dropped client connection or a platform function timeout still leaves the
 * user with every opportunity found up to that point.
 */
export async function* runScout(systemPrompt: string, ctx: ScoutContext): AsyncGenerator<ScoutEvent> {
  const messages: Anthropic.MessageParam[] = [{ role: "user", content: KICKOFF }];
  let summary = "";
  let findingCount = 0;
  let searchesUsed = 0;
  // The _20260209 web tools filter their results dynamically, which runs code
  // execution in a server-side container under the hood. Once a turn has
  // produced container-backed tool use, every subsequent request in the same
  // conversation must name that container or the API rejects it with
  // "container_id is required when there are pending tool uses generated by
  // code execution with tools". Carrying it forward is what makes the
  // multi-round research loop work at all.
  let containerId: string | null = null;

  for (let round = 0; round < MAX_ROUNDS; round++) {
    // Annotated rather than inferred: `container` is fed by containerId,
    // which is itself assigned from an event of this same stream, and TS
    // reports that round trip as a circular type reference without it.
    const params: Anthropic.MessageStreamParams = {
      model: MODEL,
      max_tokens: MAX_TOKENS,
      output_config: { effort: EFFORT },
      system: systemPrompt,
      tools: SCOUT_TOOLS,
      messages,
      container: containerId,
    };
    const stream = anthropic.messages.stream(params);

    let roundText = "";
    try {
      for await (const event of stream) {
        if (event.type === "message_delta") {
          // The container id rides the message_delta frame. It is NOT on
          // message_start, and the SDK's accumulated finalMessage leaves
          // `container` undefined in streaming mode — so this is the only
          // place to capture it.
          if (event.delta.container) containerId = event.delta.container.id;
        } else if (event.type === "content_block_delta" && event.delta.type === "text_delta") {
          roundText += event.delta.text;
          yield { type: "summary_delta", text: event.delta.text };
        } else if (event.type === "content_block_start") {
          // Server-hosted tools run inside Anthropic's infrastructure — there
          // is no round-trip through our handlers, but we still surface them
          // so the user sees the research happening rather than a dead spinner.
          const block = event.content_block;
          if (block.type === "server_tool_use") {
            if (block.name === "web_search") {
              searchesUsed++;
              const query = (block.input as { query?: string } | undefined)?.query;
              yield { type: "activity", label: "Searching the web", detail: query };
            } else if (block.name === "web_fetch") {
              const target = (block.input as { url?: string } | undefined)?.url;
              yield { type: "activity", label: "Reading funder page", detail: target };
            }
          } else if (block.type === "web_search_tool_result") {
            const content = block.content;
            if (!Array.isArray(content)) {
              yield { type: "activity", label: "Web search failed", detail: content.error_code };
            }
          } else if (block.type === "web_fetch_tool_result") {
            const content = block.content;
            if (content.type === "web_fetch_tool_result_error") {
              yield { type: "activity", label: "Couldn't read that page", detail: content.error_code };
            }
          }
        }
      }
    } catch (err) {
      if (err instanceof Anthropic.APIError) {
        yield { type: "error", message: `Research failed (${err.status}): ${err.message}` };
      } else {
        yield { type: "error", message: "Lost connection to the research agent mid-run." };
      }
      return;
    }

    summary += roundText;

    let finalMessage: Anthropic.Message;
    try {
      finalMessage = await stream.finalMessage();
    } catch (err) {
      yield { type: "error", message: err instanceof Error ? err.message : "Failed to complete the research run." };
      return;
    }

    // Safety classifiers can decline a request outright: HTTP 200, no usable
    // content. Check this before reading content blocks.
    if (finalMessage.stop_reason === "refusal") {
      yield {
        type: "error",
        message:
          "The research agent declined this request. Try rewording the project description in plainer, more concrete terms.",
      };
      return;
    }

    messages.push({ role: "assistant", content: finalMessage.content });

    if (finalMessage.stop_reason !== "tool_use") {
      yield { type: "done", summary, findingCount, searchesUsed };
      return;
    }

    const toolUseBlocks = finalMessage.content.filter(
      (b): b is Anthropic.ToolUseBlock => b.type === "tool_use",
    );

    const toolResults: Anthropic.ToolResultBlockParam[] = [];
    for (const block of toolUseBlocks) {
      const input = (block.input ?? {}) as Record<string, unknown>;
      const activity = activityForToolStart(block.name, input);
      if (activity) yield activity;

      let result: unknown;
      try {
        if (block.name === "record_funding_opportunity") {
          const { finding, error } = await recordFinding({
            supabase: ctx.supabase,
            runId: ctx.runId,
            orgId: ctx.orgId,
            input,
          });
          if (finding) {
            findingCount++;
            yield { type: "finding", finding };
            result = { recorded: true, finding_id: finding.id, total_recorded: findingCount };
          } else {
            result = { recorded: false, error };
          }
        } else if (block.name === "check_known_opportunities") {
          result = await searchOpportunities(
            { supabase: ctx.supabase, orgId: ctx.orgId, orgPlan: null },
            { query: input.query, limit: typeof input.limit === "number" ? input.limit : 5 },
          );
        } else {
          result = { error: `Unknown tool: ${block.name}` };
        }
      } catch (err) {
        result = { error: err instanceof Error ? err.message : "Tool execution failed" };
      }

      toolResults.push({
        type: "tool_result",
        tool_use_id: block.id,
        content: JSON.stringify(result),
      });
    }

    messages.push({ role: "user", content: toolResults });
  }

  // Ran out of rounds. Findings are already saved, so this is a partial
  // success, not a failure — report it as one.
  yield {
    type: "done",
    summary:
      summary ||
      "The research run hit its step limit before writing a summary. The opportunities found so far are saved below.",
    findingCount,
    searchesUsed,
  };
}
